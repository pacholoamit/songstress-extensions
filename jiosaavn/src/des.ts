/** One run of the 16 rounds over 8-byte blocks of bytes, decrypting. */
function decryptBlocks(bytes: number[]): number[] {
  const out: number[] = []
  for (let m = 0; m < bytes.length; m += 8) {
    let left = (bytes[m]! << 24) | (bytes[m + 1]! << 16) | (bytes[m + 2]! << 8) | bytes[m + 3]!
    let right = (bytes[m + 4]! << 24) | (bytes[m + 5]! << 16) | (bytes[m + 6]! << 8) | bytes[m + 7]!
    let temp = ((left >>> 4) ^ right) & 0x0f0f0f0f
    right ^= temp
    left ^= temp << 4
    temp = ((left >>> 16) ^ right) & 0x0000ffff
    right ^= temp
    left ^= temp << 16
    temp = ((right >>> 2) ^ left) & 0x33333333
    left ^= temp
    right ^= temp << 2
    temp = ((right >>> 8) ^ left) & 0x00ff00ff
    left ^= temp
    right ^= temp << 8
    temp = ((left >>> 1) ^ right) & 0x55555555
    right ^= temp
    left ^= temp << 1
    left = (left << 1) | (left >>> 31)
    right = (right << 1) | (right >>> 31)
    for (let i = 30; i !== -2; i -= 2) {
      const right1 = right ^ KEY[i]!
      const right2 = ((right >>> 4) | (right << 28)) ^ KEY[i + 1]!
      temp = left
      left = right
      right =
        temp ^
        (S2[(right1 >>> 24) & 63]! | S4[(right1 >>> 16) & 63]! | S6[(right1 >>> 8) & 63]! | S8[right1 & 63]! |
          S1[(right2 >>> 24) & 63]! | S3[(right2 >>> 16) & 63]! | S5[(right2 >>> 8) & 63]! | S7[right2 & 63]!)
    }
    temp = left
    left = right
    right = temp
    left = (left >>> 1) | (left << 31)
    right = (right >>> 1) | (right << 31)
    temp = ((left >>> 1) ^ right) & 0x55555555
    right ^= temp
    left ^= temp << 1
    temp = ((right >>> 8) ^ left) & 0x00ff00ff
    left ^= temp
    right ^= temp << 8
    temp = ((right >>> 2) ^ left) & 0x33333333
    left ^= temp
    right ^= temp << 2
    temp = ((left >>> 16) ^ right) & 0x0000ffff
    right ^= temp
    left ^= temp << 16
    temp = ((left >>> 4) ^ right) & 0x0f0f0f0f
    right ^= temp
    left ^= temp << 4
    out.push(left >>> 24, (left >>> 16) & 0xff, (left >>> 8) & 0xff, left & 0xff,
      right >>> 24, (right >>> 16) & 0xff, (right >>> 8) & 0xff, right & 0xff)
  }
  return out
}

/** The text sealed in base64 ciphertext, its PKCS#7 padding off; "" when it
 * is not whole blocks. */
export function openSealed(bytes: number[]): string {
  if (bytes.length === 0 || bytes.length % 8 !== 0) return ''
  const plain = decryptBlocks(bytes)
  const pad = plain[plain.length - 1]!
  const kept = pad > 0 && pad <= 8 ? plain.slice(0, plain.length - pad) : plain
  return String.fromCharCode(...kept)
}
